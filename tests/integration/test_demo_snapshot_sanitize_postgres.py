async def _delete_seed_rows(
    source: dict[str, object], ids: dict[str, uuid.UUID]
) -> dict[str, int]:
    """Delete EXACTLY the recorded run-owned rows (never TRUNCATE or a
    prefix sweep). Returns the remaining per-table run-row counts: all
    must be zero."""
    conn = await _connect(source)
    remaining: dict[str, int] = {}
    try:
        # Break the gateway_keys <-> key_template_revisions FK cycle.
        await conn.execute(
            "UPDATE gateway_keys SET template_revision_id = NULL "
            "WHERE id = $1",
            ids["key"],
        )
        for table in _SEED_DELETE_ORDER:
            where = _SEED_TABLES[table]
            args = _seed_args(table, ids)
            await conn.execute(
                f"DELETE FROM {table} WHERE {where}", *args
            )
        for table in sorted(_SEED_TABLES):
            where = _SEED_TABLES[table]
            args = _seed_args(table, ids)
            remaining[table] = int(await conn.fetchval(
                f"SELECT count(*) FROM {table} WHERE {where}", *args
            ))
    finally:
        await conn.close()
    return remaining


async def _copy_row_count(conn: asyncpg.Connection, table: str) -> int:
    return int(await conn.fetchval(f"SELECT count(*) FROM {table}"))


async def _copy_scan(
    conn: asyncpg.Connection, table: str, tokens: tuple[str, ...]
) -> int:
    """Rows whose ANY rendered column value contains an absence token."""
    # row_to_json(t) over the table alias: row_to_json(*) is not accepted
    # by PostgreSQL. Explicit loop: sum() cannot consume an async
    # generator (the awaited fetchvals must be accumulated synchronously
    # in a plain for loop).
    total = 0
    for tok in tokens:
        total += int(await conn.fetchval(
            f"SELECT count(*) FROM {table} AS t "
            f"WHERE row_to_json(t)::text LIKE '%' || $1 || '%'",
            tok,
        ))
    return total


async def _all_public_tables(conn: asyncpg.Connection) -> list[str]:
    rows = await conn.fetch(
        "SELECT c.relname FROM pg_class c "
        "JOIN pg_namespace n ON n.oid = c.relnamespace "
        "WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY 1"
    )
    return [r[0] for r in rows]


