async def _run_row_fingerprint(
    source: dict[str, object], ids: dict[str, uuid.UUID]
) -> dict[str, str]:
    """md5 over the exact run-owned rows: proves no source DML."""
    conn = await _connect(source)
    out: dict[str, str] = {}
    try:
        for table in sorted(_SEED_TABLES):
            where = _SEED_TABLES[table]
            args = _seed_args(table, ids)
            out[table] = str(await conn.fetchval(
                f"SELECT md5(coalesce(string_agg(t, '|' ORDER BY t), '')) "
                f"FROM (SELECT row_to_json(x)::text AS t FROM {table} x "
                f"WHERE {where}) z",
                *args,
            ))
    finally:
        await conn.close()
    return out


