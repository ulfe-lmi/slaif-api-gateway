def _find_manifests(
    custody_root: Path,
) -> list[tuple[Path, ds.SnapshotManifest]]:
    out: list[tuple[Path, ds.SnapshotManifest]] = []
    for case_dir in sorted(custody_root.iterdir()):
        if case_dir.is_symlink() or not case_dir.is_dir():
            continue
        for job_dir in ds._list_job_dirs(case_dir):
            manifest = ds._read_manifest(job_dir)
            if manifest is not None:
                out.append((job_dir, manifest))
    return out


async def _whole_copy_fingerprint(
    conn: asyncpg.Connection, tables: list[str]
) -> dict[str, str]:
    """md5 over EVERY row of every public table (whole-copy identity)."""
    out: dict[str, str] = {}
    for table in tables:
        out[table] = str(await conn.fetchval(
            "SELECT md5(coalesce(string_agg(t, '|' ORDER BY t), '')) "
            "FROM (SELECT row_to_json(x)::text AS t FROM " + table + " x) z"
        ))
    return out


# ---------------------------------------------------------------------------
# A second fresh copy cannot reuse the first copy's mapping/authority
# ---------------------------------------------------------------------------


def test_second_fresh_copy_cannot_reuse_first_mapping(
    san_env: _Env, custody: Path
) -> None:
    # The previous test promoted copy A (still private in the module
    # custody). A fresh snapshot + sanitize of the SAME source rows is
    # copy B: its different job id (seed) must yield a different identity
    # mapping and independently invalidated credentials.
    env = san_env

    async def scenario() -> None:
        prior = [
            (jd, m) for jd, m in _find_manifests(env.custody)
            if m.state == ds.STATE_DB_SANITIZED_UNPUBLISHED and m.target_db
        ]
        assert prior, "an earlier promoted sanitized copy is required"
        _, a_manifest = min(prior, key=lambda p: p[1].created_at)

        config_b = _config_for(env, custody)
        result_b = await asyncio.to_thread(ds.run_snapshot_job, config_b)
        assert result_b.state == ds.STATE_RAW_UNVERIFIED, result_b.failure_code
        raw_b = result_b.target_db
        san_b = await asyncio.to_thread(dsan.sanitize_copies, config_b)
        assert san_b.state == "SANITIZED", (san_b.state, san_b.failure_code)
        assert san_b.copies_sanitized == 1

        # `custody` is itself the case directory (job dirs directly).
        b_manifests = [
            m
            for jd in ds._list_job_dirs(custody)
            if (m := ds._read_manifest(jd)) is not None
            and m.state == ds.STATE_DB_SANITIZED_UNPUBLISHED
        ]
        assert len(b_manifests) == 1
        b_manifest = b_manifests[0]
        assert b_manifest.job_id != a_manifest.job_id
        assert b_manifest.target_db != a_manifest.target_db

        data = dsan.load_demo_identities()
        b_seed = b_manifest.job_id.encode("utf-8")
        b_maps = dsan.build_identity_maps(
            b_seed, data, owner_ids=[str(env.ids["owner"])],
            institution_ids=[], cohort_ids=[], org_ids=[], team_ids=[],
            project_ids=[], budget_ids=[], template_ids=[], admin_ids=[],
        )
        conn_a = await _connect_target_db(env, a_manifest.target_db)
        conn_b = await _connect_target_db(env, raw_b)
        try:
            a_owner = await conn_a.fetchrow("SELECT * FROM owners")
            b_owner = await conn_b.fetchrow("SELECT * FROM owners")
            # Same source row, EXACTLY B-seed's mapping (a reused A
            # mapping/seed would fail these equalities).
            assert b_owner["id"] == dsan.remap_uuid(b_seed, env.ids["owner"])
            assert b_owner["id"] != a_owner["id"]
            assert b_owner["name"] == b_maps.owner_name[str(env.ids["owner"])]
            a_key = await conn_a.fetchrow("SELECT * FROM gateway_keys")
            b_key = await conn_b.fetchrow("SELECT * FROM gateway_keys")
            assert b_key["token_hash"] == dsan.remap_str_id(
                b_seed, f"canary-hash-{CN}"
            )
            assert b_key["token_hash"] != a_key["token_hash"]
            # Idempotent re-run against the all-sanitized custody:
            # SKIPPED, no DB access, no re-exposure.
            san_b2 = await asyncio.to_thread(dsan.sanitize_copies, config_b)
            assert san_b2.state == "SKIPPED"
            assert san_b2.copies_sanitized == 0 and san_b2.copies_failed == 0
        finally:
            await conn_a.close()
            await conn_b.close()

    asyncio.run(scenario())


# ---------------------------------------------------------------------------
# Unknown schema objects are refused before any modification
# ---------------------------------------------------------------------------


def test_unknown_schema_refused_before_promotion(san_env: _Env) -> None:
    # Three fresh raw copies, each mutated AFTER the 221 snapshot: an
    # added table, an added column, an added public type. The sanitizer
    # must refuse each with SANITIZE_SCHEMA_UNKNOWN before ANY
    # modification; the copy stays RAW_UNVERIFIED with its raw canary
    # intact, and the retry is a safe repetition of the refusal.
    #
    # Each kind gets its OWN case directory directly under the module
    # custody root: the module teardown records job dirs one level below
    # the case dirs, so nested sub-custody dirs would escape cleanup.
    env = san_env

    async def scenario() -> None:
        for kind in ("table", "column", "type"):
            kind_custody = env.custody / f"case-{kind}-{uuid.uuid4().hex[:8]}"
            kind_custody.mkdir(mode=0o700)
            config = _config_for(env, kind_custody)
            result = await asyncio.to_thread(ds.run_snapshot_job, config)
            assert result.state == ds.STATE_RAW_UNVERIFIED, result.failure_code
            conn = await _connect_target_db(env, result.target_db)
            try:
                if kind == "table":
                    await conn.execute(
                        "CREATE TABLE public.zz_222x_probe (id int)"
                    )
                elif kind == "column":
                    await conn.execute(
                        "ALTER TABLE public.owners "
                        "ADD COLUMN zz_222x_probe text"
                    )
                else:
                    await conn.execute(
                        "CREATE TYPE public.zz_222x_probe AS ENUM ('a')"
                    )
            finally:
                await conn.close()
            san = await asyncio.to_thread(dsan.sanitize_copies, config)
            assert san.state == "FAILED", (kind, san.state, san.failure_code)
            assert san.failure_code == ds.CODE_SANITIZE_SCHEMA_UNKNOWN, kind
            # Refused BEFORE any modification: raw canary identity intact.
            conn = await _connect_target_db(env, result.target_db)
            try:
                assert (await _copy_scan(conn, "owners", (CN,))) == 1, kind
            finally:
                await conn.close()
            manifest = ds._read_manifest(ds._list_job_dirs(kind_custody)[0])
            assert manifest is not None
            assert manifest.state == ds.STATE_RAW_UNVERIFIED
            assert manifest.failure_code == ds.CODE_SANITIZE_SCHEMA_UNKNOWN
            # Safe retry: same refusal, no promotion.
            san2 = await asyncio.to_thread(dsan.sanitize_copies, config)
            assert san2.state == "FAILED"
            assert san2.failure_code == ds.CODE_SANITIZE_SCHEMA_UNKNOWN

    asyncio.run(scenario())


# ---------------------------------------------------------------------------
# A failed sanitizer transaction rolls back byte-identically
# ---------------------------------------------------------------------------


def test_partial_failure_rolls_back_byte_identical(
    san_env: _Env, custody: Path
) -> None:
    # An RC column holding a document that is NOT the installed capability
    # grammar aborts the sanitizer transaction. The copy must remain
    # byte-identical (data AND FKs) to
    # the state at the failed attempt, stay RAW_UNVERIFIED with
    # SANITIZE_FAILED, and retry with the same safe refusal.
    env = san_env

    async def scenario() -> None:
        config = _config_for(env, custody)
        result = await asyncio.to_thread(ds.run_snapshot_job, config)
        assert result.state == ds.STATE_RAW_UNVERIFIED, result.failure_code
        conn = await _connect_target_db(env, result.target_db)
        try:
            await conn.execute(
                "UPDATE model_routes SET capabilities = $1",
                json.dumps({"streaming": "yes"}),  # not an installed group
            )
            tables = await _all_public_tables(conn)
            before = await _whole_copy_fingerprint(conn, tables)
            fk_before = int(await conn.fetchval(
                "SELECT count(*) FROM pg_constraint c "
                "JOIN pg_namespace n ON n.oid = c.connamespace "
                "WHERE n.nspname = 'public' AND c.contype = 'f'"
            ))
        finally:
            await conn.close()
        san = await asyncio.to_thread(dsan.sanitize_copies, config)
        assert san.state == "FAILED", (san.state, san.failure_code)
        assert san.failure_code == ds.CODE_SANITIZE_FAILED
        conn = await _connect_target_db(env, result.target_db)
        try:
            tables = await _all_public_tables(conn)
            after = await _whole_copy_fingerprint(conn, tables)
            fk_after = int(await conn.fetchval(
                "SELECT count(*) FROM pg_constraint c "
                "JOIN pg_namespace n ON n.oid = c.connamespace "
                "WHERE n.nspname = 'public' AND c.contype = 'f'"
            ))
        finally:
            await conn.close()
        assert before == after, "failed sanitization left the copy modified"
        assert fk_before == fk_after, "failed sanitization left FKs dropped"
        manifest = ds._read_manifest(ds._list_job_dirs(custody)[0])
        assert manifest is not None
        assert manifest.state == ds.STATE_RAW_UNVERIFIED
        assert manifest.failure_code == ds.CODE_SANITIZE_FAILED
        # Safe idempotent retry: same refusal, still one failed copy.
        san2 = await asyncio.to_thread(dsan.sanitize_copies, config)
        assert san2.state == "FAILED"
        assert san2.failure_code == ds.CODE_SANITIZE_FAILED
        assert san2.copies_failed == 1

    asyncio.run(scenario())


# ---------------------------------------------------------------------------
# The independent verifier refuses a PUBLIC CONNECT grant
# ---------------------------------------------------------------------------


def test_verifier_refuses_public_connect(
    san_env: _Env, custody: Path
) -> None:
    # The sanitizer transaction may commit, but the INDEPENDENT verifier
    # must refuse promotion when PUBLIC CONNECT is granted on the copy:
    # the manifest stays RAW_UNVERIFIED / SANITIZE_VERIFY_FAILED and the
    # copy is never interpretable as available.
    #
    # Note: the injected GRANT CONNECT ... TO PUBLIC is target-admin ACL
    # drift, OUTSIDE the worker-only grant contract (the 221 worker never
    # grants CONNECT to PUBLIC and the verifier refuses such drift). The
    # test therefore also REVOKEs the grant in cleanup and re-proves the
    # refusal.
    env = san_env

    async def scenario() -> None:
        config = _config_for(env, custody)
        result = await asyncio.to_thread(ds.run_snapshot_job, config)
        assert result.state == ds.STATE_RAW_UNVERIFIED, result.failure_code
        admin = await _connect(env.target)
        try:
            await admin.execute(
                f'GRANT CONNECT ON DATABASE "{result.target_db}" TO PUBLIC'
            )
        finally:
            await admin.close()
        san = await asyncio.to_thread(dsan.sanitize_copies, config)
        assert san.state == "FAILED", (san.state, san.failure_code)
        assert san.failure_code == ds.CODE_SANITIZE_VERIFY_FAILED
        manifest = ds._read_manifest(ds._list_job_dirs(custody)[0])
        assert manifest is not None
        assert manifest.state == ds.STATE_RAW_UNVERIFIED
        assert manifest.failure_code == ds.CODE_SANITIZE_VERIFY_FAILED
        # The PUBLIC grant was in effect during the sanitization attempt
        # (the web role can now connect) -- the injected drift is
        # detectable -- yet promotion was refused.
        assert await _web_connect_refused(env, result.target_db) == "connected"
        # Cleanup: REVOKE the injected drift and re-prove the refusal.
        admin = await _connect(env.target)
        try:
            await admin.execute(
                f'REVOKE CONNECT ON DATABASE "{result.target_db}" FROM PUBLIC'
            )
        finally:
            await admin.close()
        assert await _web_connect_refused(env, result.target_db) == "42501"

    asyncio.run(scenario())


